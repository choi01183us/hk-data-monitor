/** Presentation reads exact period/category matches; missing values never become zero. */
export function serviceProgrammePoints(doc, programme) {
  return SERVICE_PERIODS.map(({period}) => {
    const points = doc.series.filter((row) => row.category === programme.category && row.period === period);
    if (points.length !== 1 || !Number.isSafeInteger(points[0].value) || points[0].value < 0) throw new Error(`Invalid programme value: ${programme.category} ${period}`);
    return points[0];
  });
}
